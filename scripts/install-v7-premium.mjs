// Import a local ChatGPT-created V7 ZIP or its extracted directory into actual LIVE assets.
// No third-party dependencies, no calls to internet, and NO repository writes until invoked.
import {readFile,writeFile,mkdir,stat} from 'node:fs/promises';
import {join,resolve,basename} from 'node:path';
import {inflateRawSync} from 'node:zlib';
import {createHash} from 'node:crypto';
import {pathToFileURL} from 'node:url';
export const PREMIUM_FILES=Object.freeze([
 'thunder-dragon.webp','thunder-dragon-impact.webp',
 'divine-sword-storm.webp','flame-phoenix.webp','phoenix-impact.webp',
 'taiji-seal.webp','screen-shatter.webp'
]);
const MAX_ARCHIVE=45*1024*1024;
const MAX_IMAGE=900000;
function unpackZip(data){
 if(data.length>MAX_ARCHIVE)throw Error('Archive exceeds 45 MB');
 let eocd=-1;
 for(let i=data.length-22;i>=Math.max(0,data.length-65557);i--){
  if(data.readUInt32LE(i)===0x06054b50){eocd=i;break;}
 }
 if(eocd<0)throw Error('ZIP end-of-central-directory missing');
 const count=data.readUInt16LE(eocd+10),offset=data.readUInt32LE(eocd+16);
 if(count>250||offset>=data.length)throw Error('ZIP index invalid');
 const entries=new Map();let pos=offset;
 for(let i=0;i<count;i++){
  if(pos+46>data.length||data.readUInt32LE(pos)!==0x02014b50)throw Error('ZIP central entry invalid');
  const method=data.readUInt16LE(pos+10),
  compressed=data.readUInt32LE(pos+20),uncompressed=data.readUInt32LE(pos+24),
  n=data.readUInt16LE(pos+28),ext=data.readUInt16LE(pos+30),comment=data.readUInt16LE(pos+32),
  local=data.readUInt32LE(pos+42),filename=data.toString('utf8',pos+46,pos+46+n);
  pos+=46+n+ext+comment;
  const wanted=PREMIUM_FILES.find(x=>filename.endsWith('/alpha_webp/'+x)||filename==='alpha_webp/'+x);
  if(!wanted)continue;
  if(uncompressed>MAX_IMAGE||compressed>MAX_IMAGE||entries.has(wanted))throw Error('Oversize or duplicate '+wanted);
  if(local+30>data.length||data.readUInt32LE(local)!==0x04034b50)throw Error('ZIP local header invalid');
  const start=local+30+data.readUInt16LE(local+26)+data.readUInt16LE(local+28);
  if(start+compressed>data.length)throw Error('ZIP compressed body truncated');
  const body=data.subarray(start,start+compressed);
  const bytes=method===8?inflateRawSync(body,{maxOutputLength:MAX_IMAGE}):method===0?body:null;
  if(!bytes||bytes.length!==uncompressed)throw Error('Unsupported or invalid ZIP entry '+wanted);
  entries.set(wanted,bytes);
 }
 return entries;
}
export async function readPremiumPack(input){
 const full=resolve(input);
 let files;
 if((await stat(full)).isDirectory()){
  files=new Map();
  for(const name of PREMIUM_FILES){
   let bytes;try{bytes=await readFile(join(full,'alpha_webp',name));}catch{
    bytes=await readFile(join(full,name));
   }
   files.set(name,bytes);
  }
 }else files=unpackZip(await readFile(full));
 for(const name of PREMIUM_FILES){
  const file=files.get(name);
  if(!file||file.length<1024||file.length>MAX_IMAGE)throw Error('Missing or invalid premium asset '+name);
  if(file.toString('ascii',0,4)!=='RIFF'||file.toString('ascii',8,12)!=='WEBP')throw Error('Not a WebP '+name);
 }
 return files;
}
export async function installV7Premium(pack,{root=process.cwd()}={}){
 const files=await readPremiumPack(pack);
 const directory=join(root,'public','assets','v7-premium');
 await mkdir(directory,{recursive:true});
 const manifest={version:7,files:[],source:basename(pack),installedAt:new Date().toISOString()};
 for(const name of PREMIUM_FILES){
  const bytes=files.get(name);
  await writeFile(join(directory,name),bytes);
  manifest.files.push({name,bytes:bytes.length,sha256:createHash('sha256').update(bytes).digest('hex')});
 }
 await writeFile(join(directory,'manifest.json'),JSON.stringify(manifest,null,2)+'\n');
 const config='// Generated by scripts/install-v7-premium.mjs; this file enables local alpha WebPs.\n'+
  'export const V7_PREMIUM_ENABLED=true;\n'+
  'export const V7_PREMIUM_FILES=Object.freeze('+JSON.stringify(PREMIUM_FILES)+');\n';
 await writeFile(join(root,'public','v7-premium-config.js'),config);
 return {files:manifest.files.length,bytes:manifest.files.reduce((sum,e)=>sum+e.bytes,0),directory};
}
if(process.argv[1]&&import.meta.url===pathToFileURL(resolve(process.argv[1])).href){
 const path=process.argv[2];
 if(!path){console.error('Usage: npm run assets:v7-install -- <asset-pack.zip or extracted directory>');process.exitCode=2;}
 else try{
  const result=await installV7Premium(path);
  console.log('Installed V7 alpha-art:',result.files,'files,',result.bytes,'compressed bytes at',result.directory);
 }catch(err){console.error(err.message);process.exitCode=1;}
}
